func TestPublicAndInspect(t *testing.T) {
	sk, err := key.GenerateSecretKey()
	if err != nil {
		t.Fatal(err)
	}
	seed := sk.Bytes()

	var out bytes.Buffer
	if err := run(&out, nil, []string{"public", hex.EncodeToString(seed[:])}); err != nil {
		t.Fatal(err)
	}
	text := out.String()
	for _, want := range []string{
		"public " + sk.Public().String(),
		"endpoint " + sk.Public().EndpointID().String(),
		"z32 " + sk.Public().EndpointID().Z32(),
	} {
		if !strings.Contains(text, want) {
			t.Fatalf("output missing %q:\n%s", want, text)
		}
	}

	out.Reset()
	if err := run(&out, nil, []string{"inspect", sk.Public().EndpointID().Z32()}); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.String(), "endpoint "+sk.Public().EndpointID().String()) {
		t.Fatalf("inspect output missing endpoint:\n%s", out.String())
	}
}

// TestPublicFromStdin covers the pipeline gikey documents: generate writes a
// labeled secret line, and public reads it without it reaching a command line.
func TestPublicFromStdin(t *testing.T) {
	var generated bytes.Buffer
	if err := run(&generated, nil, []string{"generate"}); err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	if err := run(&out, strings.NewReader(generated.String()), []string{"public"}); err != nil {
		t.Fatal(err)
	}
	want := publicLine(t, generated.String())
	if !strings.Contains(out.String(), want) {
		t.Fatalf("public from stdin = %q, want it to contain %q", out.String(), want)
	}
}

func TestSecretText(t *testing.T) {
	tests := []struct {
		name string
		in   string
		args []string
		want string
	}{
		{name: "argument wins", in: "ignored\n", args: []string{"abc"}, want: "abc"},
		{name: "bare line", in: "abc\n", want: "abc"},
		{name: "labeled line", in: "secret abc\n", want: "abc"},
		{name: "leading blank lines", in: "\n\nsecret abc\n", want: "abc"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := secretText(strings.NewReader(tt.in), tt.args)
			if err != nil {
				t.Fatalf("secretText: %v", err)
			}
			if got != tt.want {
				t.Fatalf("secretText = %q, want %q", got, tt.want)
			}
		})
	}
	if _, err := secretText(strings.NewReader(""), nil); err == nil {
		t.Fatal("secretText succeeded on empty stdin")
	}
}

func TestRunRejectsBadInput(t *testing.T) {
	tests := []struct {
		name string
		args []string
	}{
		{name: "no command", args: nil},
		{name: "unknown command", args: []string{"frobnicate"}},
		{name: "bad endpoint", args: []string{"inspect", "not-an-endpoint"}},
		{name: "bad secret", args: []string{"public", "not-a-secret"}},
		{name: "extra generate operand", args: []string{"generate", "extra"}},
		{name: "extra public operand", args: []string{"public", "a", "b"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if err := run(&bytes.Buffer{}, strings.NewReader(""), tt.args); err == nil {
				t.Fatalf("run(%q) succeeded, want error", tt.args)
			}
		})
	}
}

// TestRunReportsOutputError checks that a rejected write is reported rather
// than swallowed: a command that could not deliver its output has not
// succeeded.
func TestRunReportsOutputError(t *testing.T) {
	want := errors.New("write rejected")
	for _, args := range [][]string{
		{"generate"},
		{"public", "secret"},
		{"inspect", "id"},
	} {
		name := args[0]
		t.Run(name, func(t *testing.T) {
			// Use real inputs so the command reaches its output stage.
			sk, err := key.GenerateSecretKey()
			if err != nil {
				t.Fatal(err)
			}
			seed := sk.Bytes()
			switch name {
			case "public":
				args = []string{"public", hex.EncodeToString(seed[:])}
			case "inspect":
				args = []string{"inspect", sk.Public().EndpointID().String()}
			}
			err = run(errWriter{want}, strings.NewReader(""), args)
			if !errors.Is(err, want) {
				t.Fatalf("run(%q) error = %v, want %v", args, err, want)
			}
		})
	}
}

type errWriter struct{ err error }

func (w errWriter) Write([]byte) (int, error) { return 0, w.err }

// publicLine returns the "public ..." line of gikey output.
func publicLine(t *testing.T, out string) string {
	t.Helper()
	for line := range strings.SplitSeq(strings.TrimSpace(out), "\n") {
		if strings.HasPrefix(line, "public ") {
			return line
		}
	}
	t.Fatalf("no public line in %q", out)
	return ""
}
